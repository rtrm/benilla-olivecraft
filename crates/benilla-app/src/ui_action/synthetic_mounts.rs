/// Installs every reserved mount-range display row into `catalog`, called once after `Spell.dbc`
/// loads (`ui_action::load_spells`), the same place and same pattern as
/// `synthetic_spells::install`.
pub(crate) fn install(catalog: &mut SpellCatalog) {
    for id in teach_spell_ids() {
        catalog.insert(
            id,
            SpellDisplay {
                id,
                visual: TEACH_VISUAL,
                ..Default::default()
            },
        );
    }
    for &(teach_id, summon_id) in TEACHES {
        catalog.insert_learned_spell(teach_id, summon_id);
    }
    for mount in MOUNTS {
        debug_assert!(
            MOUNT_SPELL_RANGE.contains(&mount.id),
            "{} is outside MOUNT_SPELL_RANGE - the Mounts tab and click-to-cast would both miss it",
            mount.id
        );
        catalog.insert(
            mount.id,
            SpellDisplay {
                id: mount.id,
                name: mount.name.to_string(),
                icon: Some(mount.icon.to_string()),
                visual: mount.visual,
                effects: [EFFECT_APPLY_AURA, EFFECT_APPLY_AURA, 0],
                implicit_target_a1: TARGET_UNIT_CASTER,
                description: Some(mount.description.to_string()),
                aura_description: Some(mount.aura_description.to_string()),
                base_level: mount.base_level,
                effect_base_points: [mount.effect1.base_points, mount.effect2.base_points, 0],
                effect_base_dice: [mount.effect1.base_dice, mount.effect2.base_dice, 0],
                effect_die_sides: [mount.effect1.die_sides, mount.effect2.die_sides, 0],
                effect_dice_per_level: [
                    mount.effect1.dice_per_level,
                    mount.effect2.dice_per_level,
                    0,
                ],
                effect_real_points_per_level: [
                    mount.effect1.real_points_per_level,
                    mount.effect2.real_points_per_level,
                    0.0,
                ],
                effect_apply_aura: [mount.effect1.apply_aura, mount.effect2.apply_aura, 0],
                // As `synthetic_spells::install`: `targets: 0` plus the implicit-target arm above
                // ask for no target at all, casting_time_index 0 resolves to instant.
                ..Default::default()
            },
        );
    }
}
